import Foundation
import os
import Security

/// Persistent storage for the random key that encrypts the TDLib local
/// database (messages, chats, contacts, session keys).
///
/// Storage:
///   Keychain (kSecClassGenericPassword)
///   service = "orbitext.tdlib.db-encryption"
///   account = "default"
///   accessibility = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly
///     (TDLib starts well after first unlock on every boot; we do not want
///     the key to migrate to a new device via Keychain sync, since the local
///     DB cannot travel either)
///
/// Per Apple Security framework guidance, the random key material is 32 bytes
/// generated by SecRandomCopyBytes (CSPRNG). The key is base64-encoded on the
/// JSON wire for TDLib's `database_encryption_key` parameter (which is of TL
/// type `bytes`).
enum TDLibDatabaseKey {
    private static let service = "orbitext.tdlib.db-encryption"
    private static let account = "default"
    /// TDLib's database encryption uses 32-byte (256-bit) keys.
    private static let keyLength = 32

    enum KeychainError: LocalizedError {
        case status(OSStatus)
        case unexpectedItemType
        case generationFailed(OSStatus)

        var errorDescription: String? {
            switch self {
            case .status(let status):
                let message: String
                switch status {
                case errSecMissingEntitlement:
                    message = L10n.string("This version of Orbitext cannot access secure storage. Install a properly signed version of the app.")
                case errSecInteractionNotAllowed:
                    message = L10n.string("Secure storage cannot be accessed right now. Unlock your Apple Watch, then try again.")
                case errSecNotAvailable:
                    message = L10n.string("Secure storage is unavailable. Try again in a moment.")
                default:
                    message = L10n.string("Could not access the encryption key in secure storage. Try again. If this continues, contact support.")
                }
                return message + "\n\n" + Self.diagnostic(status)
            case .unexpectedItemType:
                return L10n.string("The encryption key in secure storage could not be read. Contact support before changing or reinstalling the app.")
            case .generationFailed(let status):
                return L10n.string("Could not create a secure encryption key. Try again. If this continues, contact support.")
                    + "\n\n" + Self.diagnostic(status)
            }
        }

        private static func diagnostic(_ status: OSStatus) -> String {
            // Keep the actual Security status, including unknown future values.
            // A Swift Error's synthesized NSError code is only an enum case index.
            let code = "Keychain / Security (OSStatus \(status))"
            guard let reason = SecCopyErrorMessageString(status, nil) as String?, !reason.isEmpty else {
                return code
            }
            return code + ": " + reason
        }
    }

    /// Generate a new 32-byte random key. Crashes only on CSPRNG failure,
    /// which Apple documents as impossible on real hardware.
    static func generate() throws -> Data {
        var bytes = [UInt8](repeating: 0, count: keyLength)
        let status = SecRandomCopyBytes(kSecRandomDefault, keyLength, &bytes)
        guard status == errSecSuccess else { throw KeychainError.generationFailed(status) }
        return Data(bytes)
    }

    /// Load the stored key, or nil if no key is stored. Throws on Keychain
    /// errors other than "not found".
    static func load() throws -> Data? {
        var query: [String: Any] = baseQuery()
        query[kSecReturnData as String] = true
        query[kSecMatchLimit as String] = kSecMatchLimitOne

        var item: CFTypeRef?
        let status = SecItemCopyMatching(query as CFDictionary, &item)
        switch status {
        case errSecSuccess:
            guard let data = item as? Data else { throw KeychainError.unexpectedItemType }
            return data
        case errSecItemNotFound:
            return nil
        default:
            throw KeychainError.status(status)
        }
    }

    /// Store the given key, overwriting any prior value. Idempotent.
    static func store(_ key: Data) throws {
        // Try update first.
        let updateQuery = baseQuery()
        let updateAttrs: [String: Any] = [kSecValueData as String: key]
        let updateStatus = SecItemUpdate(updateQuery as CFDictionary, updateAttrs as CFDictionary)

        switch updateStatus {
        case errSecSuccess:
            return
        case errSecItemNotFound:
            // Fall through to add.
            break
        default:
            throw KeychainError.status(updateStatus)
        }

        var addQuery = baseQuery()
        addQuery[kSecValueData as String] = key
        addQuery[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly

        let addStatus = SecItemAdd(addQuery as CFDictionary, nil)
        guard addStatus == errSecSuccess else { throw KeychainError.status(addStatus) }
    }

    /// Remove the stored key. Used by force-logout / DB-purge paths so a fresh
    /// install starts with a fresh key.
    static func remove() throws {
        let status = SecItemDelete(baseQuery() as CFDictionary)
        switch status {
        case errSecSuccess, errSecItemNotFound:
            return
        default:
            throw KeychainError.status(status)
        }
    }

    /// Resolve the key to use at TDLib start. Returns the chosen key plus a
    /// flag indicating whether a legacy (unencrypted) TDLib database must be
    /// re-encrypted via setDatabaseEncryptionKey after authorizationStateReady.
    ///
    /// Cases:
    ///   - Keychain has a key                 -> use it, no migration
    ///   - Keychain empty + DB binlog exists  -> use empty key (open legacy
    ///                                            unencrypted DB), migration
    ///                                            needed
    ///   - Keychain empty + no DB             -> generate and store fresh key,
    ///                                            encrypt from creation
    static func resolveAtStart(
        databaseDirectory: URL,
        loadKey: () throws -> Data? = Self.load,
        storeKey: (Data) throws -> Void = Self.store,
        generateKey: () throws -> Data = Self.generate,
        fileExists: (String) -> Bool = { FileManager.default.fileExists(atPath: $0) }
    ) throws -> (key: Data, needsMigration: Bool) {
        if let existing = try loadKey() {
            return (existing, false)
        }

        let binlog = databaseDirectory.appendingPathComponent("td.binlog")
        let hasLegacyDB = fileExists(binlog.path)
        if hasLegacyDB {
            Logger.tdlib.info("TDLib DB key: legacy unencrypted DB detected, will migrate after ready")
            return (Data(), true)
        }

        let fresh = try generateKey()
        try storeKey(fresh)
        Logger.tdlib.info("TDLib DB key: fresh install, generated and stored new 32-byte key")
        return (fresh, false)
    }

    private static func baseQuery() -> [String: Any] {
        [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: account
        ]
    }
}
